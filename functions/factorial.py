import math


# =========================================================
# Factorial
# =========================================================

def factorial(value):
    """
    حساب العامل لعدد صحيح غير سالب.

    Parameters
    ----------
    value:
        العدد المراد حساب عامله.

    Returns
    -------
    int
        قيمة العامل.

    Raises
    ------
    TypeError
        إذا لم يكن الإدخال عددًا صحيحًا.

    ValueError
        إذا كان العدد سالبًا.

    Examples
    --------
    factorial(5) -> 120
    factorial(0) -> 1
    """

    # -----------------------------------------------------
    # يجب أن يكون العدد صحيحًا
    # -----------------------------------------------------

    if isinstance(value, bool) or not isinstance(value, int):

        raise TypeError(
            "Factorial is defined for integers only."
        )

    # -----------------------------------------------------
    # العامل غير معرف للأعداد السالبة
    # -----------------------------------------------------

    if value < 0:

        raise ValueError(
            "Factorial is not defined for negative integers."
        )

    # -----------------------------------------------------
    # حساب العامل
    # -----------------------------------------------------

    return math.factorial(value)