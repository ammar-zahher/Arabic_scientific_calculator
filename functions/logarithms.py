import math


# =========================================================
# Base-10 Logarithm
# =========================================================

def log10(value):
    """
    حساب اللوغاريتم العشري.

    log10(x) = log(x) إلى الأساس 10

    Parameters
    ----------
    value:
        العدد المراد حساب لوغاريتمه.

    Returns
    -------
    float
        اللوغاريتم العشري للعدد.

    Raises
    ------
    ValueError
        إذا كان العدد أصغر من أو يساوي صفرًا.

    Examples
    --------
    log10(100) -> 2.0
    log10(1000) -> 3.0
    """

    return math.log10(value)


# =========================================================
# Natural Logarithm
# =========================================================

def ln(value):
    """
    حساب اللوغاريتم الطبيعي.

    ln(x) = log(x) إلى الأساس e

    Parameters
    ----------
    value:
        العدد المراد حساب لوغاريتمه الطبيعي.

    Returns
    -------
    float
        اللوغاريتم الطبيعي للعدد.

    Raises
    ------
    ValueError
        إذا كان العدد أصغر من أو يساوي صفرًا.

    Examples
    --------
    ln(1) -> 0.0
    ln(e) -> 1.0
    """

    return math.log(value)