# =========================================================
# Complex Conversion
# =========================================================

def to_complex(value):
    """
    تحويل القيمة إلى عدد مركب.

    Parameters
    ----------
    value:
        قيمة عددية حقيقية أو مركبة.

    Returns
    -------
    complex
        القيمة على شكل complex.

    Examples
    --------
    to_complex(5) -> (5+0j)
    to_complex(2.5) -> (2.5+0j)
    to_complex(3 + 4j) -> (3+4j)
    """

    return complex(value)


# =========================================================
# Addition
# =========================================================

def complex_add(a, b):
    """
    جمع عددين حقيقيين أو مركبين.

    Examples
    --------
    complex_add(2, 3) -> (5+0j)
    complex_add(2 + 3j, 4 + 5j) -> (6+8j)
    """

    return complex(a) + complex(b)


# =========================================================
# Subtraction
# =========================================================

def complex_subtract(a, b):
    """
    طرح العدد الثاني من العدد الأول.

    Examples
    --------
    complex_subtract(5, 2) -> (3+0j)
    complex_subtract(2 + 3j, 1 + 2j) -> (1+1j)
    """

    return complex(a) - complex(b)


# =========================================================
# Multiplication
# =========================================================

def complex_multiply(a, b):
    """
    ضرب عددين حقيقيين أو مركبين.

    Examples
    --------
    complex_multiply(2, 3) -> (6+0j)
    complex_multiply(2 + 3j, 4 + 5j) -> (-7+22j)
    """

    return complex(a) * complex(b)


# =========================================================
# Division
# =========================================================

def complex_divide(a, b):
    """
    قسمة عدد على عدد آخر.

    Raises
    ------
    ZeroDivisionError
        إذا كان المقام صفرًا.

    Examples
    --------
    complex_divide(6, 2) -> (3+0j)
    """

    return complex(a) / complex(b)


# =========================================================
# Power
# =========================================================

def complex_power(base, exponent):
    """
    حساب قوة عدد حقيقي أو مركب.

    Python يتولى الحساب في المجال المركب.

    Examples
    --------
    complex_power(2, 3) -> (8+0j)
    complex_power(1j, 2) -> (-1+0j)
    """

    return complex(base) ** complex(exponent)