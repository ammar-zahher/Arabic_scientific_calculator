import math


# =========================================================
# Power
# =========================================================

def power(base, exponent):
    """
    حساب القوة.

    Parameters
    ----------
    base:
        الأساس.

    exponent:
        الأس.

    Returns
    -------
    عدد ناتج عن:
        base ** exponent

    Examples
    --------
    power(2, 3) -> 8
    power(5, 2) -> 25
    power(2, -3) -> 0.125
    """

    return base ** exponent


# =========================================================
# Square Root
# =========================================================

def square_root(value):
    """
    حساب الجذر التربيعي.

    Parameters
    ----------
    value:
        العدد المراد حساب جذره التربيعي.

    Returns
    -------
    الجذر التربيعي للعدد.

    Raises
    ------
    ValueError
        إذا كان العدد سالبًا في المجال الحقيقي.

    Examples
    --------
    square_root(25) -> 5.0
    square_root(9) -> 3.0
    """

    return math.sqrt(value)


# =========================================================
# Cube Root
# =========================================================

def cube_root(value):
    """
    حساب الجذر التكعيبي.

    يدعم الأعداد السالبة أيضًا.

    Examples
    --------
    cube_root(27) -> 3.0
    cube_root(8) -> 2.0
    cube_root(-8) -> -2.0
    """

    return math.cbrt(value)